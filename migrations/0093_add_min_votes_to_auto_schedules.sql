-- 日程調整の「最少開催人数」(定足数) を設定可能にする。
--
-- 背景:
--   投票を締め切った時、最多得票日でも参加者が少なすぎると開催しても
--   集まらない。これまでは票数に関わらず最多得票日を winner として
--   リマインダを登録していたため、実質参加不能な回でも「開催します」の
--   リマインドが飛んでいた。最多得票数が閾値未満なら開催を見送る。
--
-- 設計:
--   - min_votes: 開催に必要な最少得票数 (定足数)。締切時の最多得票数が
--     これ未満なら winner リマインダ登録を skip し、中止メッセージを投稿する。
--   - NOT NULL DEFAULT 3: 既存 auto_schedules 行はすべて 3 にバックフィル。
--     3 固定を避け、行ごとに設定変更できるようにする (0 にすれば常に開催)。
--
-- 互換性:
--   DEFAULT 付き NOT NULL カラムの追加なので既存行・全 API は壊れない。

ALTER TABLE `auto_schedules` ADD COLUMN `min_votes` integer NOT NULL DEFAULT 3;
